-- Private teachers get their own space: a tenant of kind INDIVIDUAL created by a public sign-up.
ALTER TABLE tenants ADD COLUMN kind VARCHAR(20) NOT NULL DEFAULT 'SCHOOL';
ALTER TABLE tenants ADD CONSTRAINT ck_tenants_kind CHECK (kind IN ('SCHOOL', 'INDIVIDUAL'));

-- Null only for self sign-ups that have not opened the confirmation link yet.
-- Users created by an admin, a teacher or the operator are confirmed when created.
ALTER TABLE users ADD COLUMN email_confirmed_at TIMESTAMPTZ;
UPDATE users SET email_confirmed_at = created_at;

-- Single-use confirmation links; only the SHA-256 of the token is stored.
CREATE TABLE email_confirmations (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id  BIGINT      NOT NULL REFERENCES tenants (id) ON DELETE CASCADE,
    user_id    BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    token_hash VARCHAR(64) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    used_at    TIMESTAMPTZ,
    CONSTRAINT uk_email_confirmations_token UNIQUE (token_hash)
);
CREATE INDEX ix_email_confirmations_user ON email_confirmations (user_id, created_at);
CREATE INDEX ix_tenants_kind_created ON tenants (kind, created_at);
