-- The level scale is data, not code: a future change (another scale, or one per school through a
-- nullable tenant_id) adds rows and deactivates old ones. Inactive levels stay on existing tasks.
CREATE TABLE levels (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code     VARCHAR(20)  NOT NULL,
    name     VARCHAR(100) NOT NULL,
    position INTEGER      NOT NULL,
    active   BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_levels_code UNIQUE (code)
);

