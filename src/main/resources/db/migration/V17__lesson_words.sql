-- New words of a lesson, listed by its teacher. Each word can be sent once to the student's flashcards
-- and once to a sentence-writing task; the timestamps record when.
CREATE TABLE lesson_words (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id          BIGINT        NOT NULL REFERENCES tenants (id),
    lesson_id          BIGINT        NOT NULL REFERENCES lessons (id) ON DELETE CASCADE,
    word               VARCHAR(200)  NOT NULL,
    meaning            VARCHAR(1000) NOT NULL,
    created_at         TIMESTAMPTZ   NOT NULL,
    flashcard_sent_at  TIMESTAMPTZ,
    task_sent_at       TIMESTAMPTZ
);

CREATE INDEX ix_lesson_words_lesson ON lesson_words (lesson_id, id);
