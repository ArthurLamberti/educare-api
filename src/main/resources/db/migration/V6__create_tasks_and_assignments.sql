CREATE TABLE tasks (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id    BIGINT         NOT NULL REFERENCES tenants (id),
    teacher_id   BIGINT         NOT NULL REFERENCES users (id),
    title        VARCHAR(200)   NOT NULL,
    instructions VARCHAR(10000) NOT NULL,
    archived     BOOLEAN        NOT NULL DEFAULT FALSE,
    created_at   TIMESTAMPTZ    NOT NULL,
    updated_at   TIMESTAMPTZ    NOT NULL
);

CREATE INDEX ix_tasks_teacher ON tasks (teacher_id, created_at);

CREATE TABLE assignments (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id   BIGINT      NOT NULL REFERENCES tenants (id),
    task_id     BIGINT      NOT NULL REFERENCES tasks (id),
    student_id  BIGINT      NOT NULL REFERENCES students (id),
    due_at      TIMESTAMPTZ,
    status      VARCHAR(20) NOT NULL,
    assigned_at TIMESTAMPTZ NOT NULL,
    -- SUBMITTED and GRADED are used from change 07 on.
    CONSTRAINT ck_assignments_status CHECK (status IN ('ASSIGNED', 'SUBMITTED', 'GRADED'))
);

-- A student cannot have the same task twice while it is still to do.
CREATE UNIQUE INDEX ux_assignments_open ON assignments (task_id, student_id) WHERE status = 'ASSIGNED';
CREATE INDEX ix_assignments_student ON assignments (student_id, due_at);
