CREATE TABLE tenants (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug       VARCHAR(40)  NOT NULL,
    name       VARCHAR(150) NOT NULL,
    time_zone  VARCHAR(64)  NOT NULL,
    created_at TIMESTAMPTZ  NOT NULL,
    CONSTRAINT uk_tenants_slug UNIQUE (slug),
    CONSTRAINT ck_tenants_slug CHECK (slug ~ '^[a-z0-9][a-z0-9-]{1,38}[a-z0-9]$')
);

-- Emails are stored lowercased (enforced by ck_users_email_lower), so the plain unique
-- constraint is case-insensitive in practice.
CREATE TABLE users (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id            BIGINT       NOT NULL REFERENCES tenants (id),
    name                 VARCHAR(150) NOT NULL,
    email                VARCHAR(255) NOT NULL,
    password_hash        VARCHAR(100) NOT NULL,
    role                 VARCHAR(20)  NOT NULL,
    must_change_password BOOLEAN      NOT NULL,
    active               BOOLEAN      NOT NULL,
    created_at           TIMESTAMPTZ  NOT NULL,
    CONSTRAINT uk_users_tenant_email UNIQUE (tenant_id, email),
    CONSTRAINT ck_users_email_lower CHECK (email = lower(email)),
    CONSTRAINT ck_users_role CHECK (role IN ('ADMIN', 'TEACHER', 'STUDENT'))
);
