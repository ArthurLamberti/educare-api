-- Students become user accounts (role STUDENT) with a profile owned by a teacher.
-- The original standalone table is dropped: no production data existed when this ran.
DROP TABLE students;

CREATE TABLE students (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id  BIGINT NOT NULL REFERENCES tenants (id),
    user_id    BIGINT NOT NULL REFERENCES users (id),
    teacher_id BIGINT NOT NULL REFERENCES users (id),
    birth_date DATE,
    CONSTRAINT uk_students_user UNIQUE (user_id)
);

CREATE INDEX ix_students_teacher ON students (teacher_id);
