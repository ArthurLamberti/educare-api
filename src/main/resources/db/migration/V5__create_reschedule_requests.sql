CREATE TABLE reschedule_requests (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id          BIGINT       NOT NULL REFERENCES tenants (id),
    lesson_id          BIGINT       NOT NULL REFERENCES lessons (id),
    requested_by       BIGINT       NOT NULL REFERENCES users (id),
    original_starts_at TIMESTAMPTZ  NOT NULL,
    proposed_starts_at TIMESTAMPTZ  NOT NULL,
    reason             VARCHAR(500),
    status             VARCHAR(20)  NOT NULL,
    decision_note      VARCHAR(500),
    decided_by         BIGINT REFERENCES users (id),
    decided_at         TIMESTAMPTZ,
    created_at         TIMESTAMPTZ  NOT NULL,
    CONSTRAINT ck_reschedule_requests_status
        CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED', 'WITHDRAWN', 'CANCELED'))
);

-- At most one pending request per lesson.
CREATE UNIQUE INDEX ux_reschedule_requests_pending ON reschedule_requests (lesson_id) WHERE status = 'PENDING';
CREATE INDEX ix_reschedule_requests_lesson ON reschedule_requests (lesson_id);
