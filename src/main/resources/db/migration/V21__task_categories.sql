-- Each teacher's own categories for their task library. Names are unique per teacher ignoring case
-- (stored trimmed). Deleting a category leaves its tasks without one.
CREATE TABLE task_categories (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id  BIGINT      NOT NULL REFERENCES tenants (id),
    teacher_id BIGINT      NOT NULL REFERENCES users (id),
    name       VARCHAR(60) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL
);

CREATE UNIQUE INDEX ux_task_categories_teacher_name ON task_categories (tenant_id, teacher_id, lower(name));

ALTER TABLE tasks ADD COLUMN category_id BIGINT REFERENCES task_categories (id) ON DELETE SET NULL;
CREATE INDEX ix_tasks_category ON tasks (category_id);
