CREATE TABLE submissions (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id             BIGINT         NOT NULL REFERENCES tenants (id),
    assignment_id         BIGINT         NOT NULL REFERENCES assignments (id),
    answer                VARCHAR(20000) NOT NULL,
    -- The task instructions as the student saw them at the first submission.
    instructions_snapshot VARCHAR(10000) NOT NULL,
    submitted_at          TIMESTAMPTZ    NOT NULL,
    updated_at            TIMESTAMPTZ    NOT NULL,
    late                  BOOLEAN        NOT NULL,
    score                 NUMERIC(3, 1),
    feedback              VARCHAR(10000),
    graded_at             TIMESTAMPTZ,
    graded_by             BIGINT REFERENCES users (id),
    version               BIGINT         NOT NULL DEFAULT 0,
    CONSTRAINT ux_submissions_assignment UNIQUE (assignment_id),
    CONSTRAINT ck_submissions_score CHECK (score BETWEEN 0 AND 10),
    CONSTRAINT ck_submissions_grade CHECK ((score IS NULL) = (graded_at IS NULL))
);
