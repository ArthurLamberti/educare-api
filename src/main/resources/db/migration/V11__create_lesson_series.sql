-- Recurring lessons: on some weekdays at a fixed school-local time, with no end date. Lessons are
-- created a few weeks ahead (generated_until) and extended by a daily job; ended_at stops the series.
CREATE TABLE lesson_series (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id        BIGINT        NOT NULL REFERENCES tenants (id),
    teacher_id       BIGINT        NOT NULL REFERENCES users (id),
    student_id       BIGINT        NOT NULL REFERENCES students (id),
    -- Comma-separated java.time.DayOfWeek names, e.g. 'TUESDAY,THURSDAY'.
    weekdays         VARCHAR(80)   NOT NULL,
    start_time       TIME          NOT NULL,
    duration_minutes INTEGER       NOT NULL,
    topic            VARCHAR(200)  NOT NULL,
    notes            VARCHAR(2000),
    starts_on        DATE          NOT NULL,
    generated_until  DATE          NOT NULL,
    ended_at         TIMESTAMPTZ,
    created_at       TIMESTAMPTZ   NOT NULL,
    updated_at       TIMESTAMPTZ   NOT NULL,
    CONSTRAINT ck_lesson_series_duration CHECK (duration_minutes BETWEEN 15 AND 240)
);

CREATE INDEX ix_lesson_series_teacher ON lesson_series (teacher_id);
CREATE INDEX ix_lesson_series_open ON lesson_series (generated_until) WHERE ended_at IS NULL;

ALTER TABLE lessons ADD COLUMN series_id BIGINT REFERENCES lesson_series (id);
CREATE INDEX ix_lessons_series ON lessons (series_id, starts_at);
