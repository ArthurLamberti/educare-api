CREATE TABLE decks (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id   BIGINT        NOT NULL REFERENCES tenants (id),
    teacher_id  BIGINT        NOT NULL REFERENCES users (id),
    title       VARCHAR(200)  NOT NULL,
    description VARCHAR(2000),
    archived    BOOLEAN       NOT NULL DEFAULT FALSE,
    created_at  TIMESTAMPTZ   NOT NULL,
    updated_at  TIMESTAMPTZ   NOT NULL
);

CREATE INDEX ix_decks_teacher ON decks (teacher_id, created_at);

CREATE TABLE cards (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id  BIGINT        NOT NULL REFERENCES tenants (id),
    deck_id    BIGINT        NOT NULL REFERENCES decks (id),
    front      VARCHAR(1000) NOT NULL,
    back       VARCHAR(1000) NOT NULL,
    position   INTEGER       NOT NULL,
    created_at TIMESTAMPTZ   NOT NULL,
    updated_at TIMESTAMPTZ   NOT NULL,
    -- Deferred so a reorder can rewrite all positions in one transaction.
    CONSTRAINT ux_cards_position UNIQUE (deck_id, position) DEFERRABLE INITIALLY DEFERRED
);

-- Decks proposed to students. Removing a row hides the deck; review history (change 09) is kept.
CREATE TABLE deck_students (
    deck_id     BIGINT      NOT NULL REFERENCES decks (id),
    student_id  BIGINT      NOT NULL REFERENCES students (id),
    tenant_id   BIGINT      NOT NULL REFERENCES tenants (id),
    assigned_at TIMESTAMPTZ NOT NULL,
    PRIMARY KEY (deck_id, student_id)
);

CREATE INDEX ix_deck_students_student ON deck_students (student_id);
