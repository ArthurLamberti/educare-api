-- People who operate the platform (activate and suspend spaces). Not part of any tenant.
CREATE TABLE platform_admins (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(150) NOT NULL,
    email         VARCHAR(255) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    active        BOOLEAN      NOT NULL,
    created_at    TIMESTAMPTZ  NOT NULL,
    CONSTRAINT uk_platform_admins_email UNIQUE (email),
    CONSTRAINT ck_platform_admins_email_lower CHECK (email = lower(email))
);

-- Single-use "forgot password" links, for a tenant user or a platform admin; only the SHA-256 is stored.
CREATE TABLE password_resets (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           BIGINT REFERENCES users (id) ON DELETE CASCADE,
    platform_admin_id BIGINT REFERENCES platform_admins (id) ON DELETE CASCADE,
    token_hash        VARCHAR(64) NOT NULL,
    created_at        TIMESTAMPTZ NOT NULL,
    expires_at        TIMESTAMPTZ NOT NULL,
    used_at           TIMESTAMPTZ,
    CONSTRAINT uk_password_resets_token UNIQUE (token_hash),
    CONSTRAINT ck_password_resets_owner CHECK ((user_id IS NULL) <> (platform_admin_id IS NULL))
);
CREATE INDEX ix_password_resets_user ON password_resets (user_id);
CREATE INDEX ix_password_resets_admin ON password_resets (platform_admin_id);
