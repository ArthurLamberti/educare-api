-- Flashcards belong to one student instead of shared decks. Each card holds that student's
-- spaced-repetition state (due_at null = new card). Decks and their reviews are dropped.
DROP TABLE review_events;
DROP TABLE card_reviews;
DROP TABLE deck_students;
DROP TABLE cards;
DROP TABLE decks;

CREATE TABLE cards (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id        BIGINT        NOT NULL REFERENCES tenants (id),
    student_id       BIGINT        NOT NULL REFERENCES students (id),
    front            VARCHAR(1000) NOT NULL,
    back             VARCHAR(1000) NOT NULL,
    ease             NUMERIC(4, 2) NOT NULL DEFAULT 2.50,
    interval_days    INTEGER       NOT NULL DEFAULT 0,
    repetitions      INTEGER       NOT NULL DEFAULT 0,
    due_at           TIMESTAMPTZ,
    last_reviewed_at TIMESTAMPTZ,
    -- School day of the first rating, for the daily allowance of new cards.
    introduced_on    DATE,
    created_at       TIMESTAMPTZ   NOT NULL,
    updated_at       TIMESTAMPTZ   NOT NULL,
    CONSTRAINT ck_cards_ease CHECK (ease >= 1.30)
);

CREATE INDEX ix_cards_student ON cards (student_id, id);
CREATE INDEX ix_cards_student_due ON cards (student_id, due_at) WHERE due_at IS NOT NULL;

-- Every rating, for activity counters.
CREATE TABLE review_events (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id           BIGINT      NOT NULL REFERENCES tenants (id),
    student_id          BIGINT      NOT NULL REFERENCES students (id),
    card_id             BIGINT      NOT NULL REFERENCES cards (id) ON DELETE CASCADE,
    rating              VARCHAR(10) NOT NULL,
    reviewed_at         TIMESTAMPTZ NOT NULL,
    interval_days_after INTEGER     NOT NULL,
    CONSTRAINT ck_review_events_rating CHECK (rating IN ('AGAIN', 'HARD', 'GOOD', 'EASY'))
);

CREATE INDEX ix_review_events_student ON review_events (student_id, reviewed_at);
CREATE INDEX ix_review_events_card ON review_events (card_id);
