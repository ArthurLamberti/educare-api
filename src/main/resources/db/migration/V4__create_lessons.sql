CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE lessons (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id        BIGINT        NOT NULL REFERENCES tenants (id),
    teacher_id       BIGINT        NOT NULL REFERENCES users (id),
    student_id       BIGINT        NOT NULL REFERENCES students (id),
    starts_at        TIMESTAMPTZ   NOT NULL,
    duration_minutes INTEGER       NOT NULL,
    ends_at          TIMESTAMPTZ   NOT NULL,
    topic            VARCHAR(200)  NOT NULL,
    notes            VARCHAR(2000),
    status           VARCHAR(20)   NOT NULL,
    created_at       TIMESTAMPTZ   NOT NULL,
    updated_at       TIMESTAMPTZ   NOT NULL,
    CONSTRAINT ck_lessons_duration CHECK (duration_minutes BETWEEN 15 AND 240),
    CONSTRAINT ck_lessons_ends_at CHECK (ends_at = starts_at + make_interval(mins => duration_minutes)),
    CONSTRAINT ck_lessons_status CHECK (status IN ('SCHEDULED', 'CANCELED')),
    -- No double booking, even under concurrent requests. '[)' ranges allow back-to-back lessons.
    CONSTRAINT ex_lessons_teacher_overlap EXCLUDE USING gist (
        teacher_id WITH =, tstzrange(starts_at, ends_at) WITH &&
    ) WHERE (status = 'SCHEDULED'),
    CONSTRAINT ex_lessons_student_overlap EXCLUDE USING gist (
        student_id WITH =, tstzrange(starts_at, ends_at) WITH &&
    ) WHERE (status = 'SCHEDULED')
);

CREATE INDEX ix_lessons_teacher_starts ON lessons (teacher_id, starts_at);
CREATE INDEX ix_lessons_student_starts ON lessons (student_id, starts_at);
